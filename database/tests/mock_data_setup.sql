CREATE OR REPLACE FUNCTION mock_as_authenticated(test_user_name text)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  resolved_user_id uuid;
BEGIN
  resolved_user_id := CASE test_user_name
    WHEN 'Owner' THEN '00000000-0000-0000-0000-000000000001'::uuid
    WHEN 'Admin' THEN '00000000-0000-0000-0000-000000000002'::uuid
    WHEN 'Member' THEN '00000000-0000-0000-0000-000000000003'::uuid
    WHEN 'Invited' THEN '00000000-0000-0000-0000-000000000004'::uuid
    WHEN 'Invited2' THEN '00000000-0000-0000-0000-000000000006'::uuid
    WHEN 'Stranger' THEN '00000000-0000-0000-0000-000000000005'::uuid
    ELSE NULL
  END;

  IF resolved_user_id IS NULL THEN
    RAISE EXCEPTION 'Unsupported test user "%". Allowed: Owner, Admin, Member, Invited, Invited2, Stranger', test_user_name;
  END IF;

  PERFORM set_config('request.jwt.claim.sub', resolved_user_id::text, true);
  PERFORM set_config('role', 'authenticated', true);
  PERFORM set_config('row_security', 'on', true);
END;
$$;
GRANT EXECUTE ON FUNCTION mock_as_authenticated(text) TO authenticated;


